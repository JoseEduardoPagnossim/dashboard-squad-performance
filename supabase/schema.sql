-- Helpers de autorizacao. SECURITY DEFINER evita recursao de RLS ao consultar profiles.
create or replace function public.current_profile()
returns public.profiles
language sql
stable
security definer
set search_path = public
as $$
  select p from public.profiles p
  where p.user_id = (select auth.uid()) and p.active = true
  limit 1;
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.user_id = (select auth.uid())
      and p.active = true
      and p.role = 'super_admin'
  );
$$;

create or replace function public.can_read_squad(target_squad uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    join public.squads s on s.id = target_squad
    where p.user_id = (select auth.uid())
      and p.active = true
      and p.organization_id = s.organization_id
      and (
        p.role = 'super_admin'
        or p.squad_id = target_squad
      )
  );
$$;

create or replace function public.can_admin_squad(target_squad uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
